"""Daily digest per user: new roles in their categories above their match
threshold, as Markdown (and email when SMTP is configured)."""
from __future__ import annotations

import logging
import os
import re
import smtplib
from datetime import datetime
from email.message import EmailMessage
from pathlib import Path

from . import db

log = logging.getLogger("jobradar.digest")
DIGEST_DIR = Path(__file__).resolve().parent.parent / "digests"


def _money(n) -> str:
    return f"${int(n/1000)}k" if n else ""


def _slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", (name or "user").lower()).strip("-") or "user"


def build(cfg: dict, uid: int) -> tuple[str, dict]:
    user = db.get_user(uid) or {"id": uid, "name": "Me", "prefs": {}}
    dcfg = cfg.get("digest") or {}
    hours = int(dcfg.get("hours", 24))
    threshold = int(dcfg.get("min_match", 60))
    top_n = int(dcfg.get("max_jobs", 25))
    cats = user["prefs"].get("categories") or []
    secs = user["prefs"].get("sectors") or []
    has_resume = bool(db.get_setting("resume_text", uid))
    rows = db.digest_jobs(uid, hours=hours, min_match=threshold if has_resume else 0, categories=cats, limit=top_n,
                          sectors=secs, no_travel=user["prefs"].get("no_travel", True))
    s = db.status(uid, categories=cats)
    now = datetime.now()
    labels = {k: c.get("label", k) for k, c in (cfg.get("categories") or {}).items()}
    slabels = {k: c.get("label", k) for k, c in (cfg.get("sectors") or {}).items()}
    scope = ", ".join(labels.get(k, k) for k in cats) if cats else "all categories"
    if secs:
        scope += " · " + ", ".join(slabels.get(k, k) for k in secs)
    lines = [f"# JobRadar digest for {user['name']} — {now:%A %d %B %Y, %H:%M}", ""]
    lines.append(f"**{s['new_last_24h']}** new roles in {scope} in the last 24 h · **{s['total_jobs']}** tracked · "
                 f"**{s['saved']}** saved · **{s['applied']}** applied")
    lines.append("")
    lines.append(f"## Best new matches (≥ {threshold}% match, last {hours} h)" if has_resume
                 else f"## New roles (last {hours} h) — upload a resume to rank these by fit")
    lines.append("")
    if not rows:
        lines.append("_Nothing new above the threshold. Widen the categories or lower `digest.min_match`._")
    for j in rows:
        badge = []
        if j.get("match_score") is not None:
            badge.append(f"**{j['match_score']}%**")
        if j.get("easy_apply") == 1:
            badge.append("⚡ easy apply")
        if j.get("is_remote"):
            badge.append("remote")
        if _money(j.get("salary_annual")):
            badge.append(_money(j["salary_annual"]))
        meta = " · ".join(badge)
        sec = slabels.get(j.get("sector") or "", "")
        lines.append(f"- [{j['title']}]({j['url']}) — {j.get('company') or 'Unknown'}"
                     f"{', ' + j['location'] if j.get('location') else ''} · {j.get('level') or ''}"
                     f"{' · ' + sec if sec and j.get('sector') != 'other' else ''}"
                     f"{' · ' + meta if meta else ''}")
    lines += ["", "---", "_Generated by JobRadar. Dashboard: http://localhost:8000_"]
    md = "\n".join(lines)
    DIGEST_DIR.mkdir(exist_ok=True)
    path = DIGEST_DIR / f"{now:%Y-%m-%d}-{_slug(user['name'])}.md"
    path.write_text(md, encoding="utf-8")
    db.set_setting("last_digest_at", now.isoformat(timespec="seconds"), uid)
    db.set_setting("last_digest_path", str(path), uid)
    return md, {"path": str(path), "jobs": len(rows), "threshold": threshold, "user": user["name"]}


def send_email(cfg: dict, md: str, to: str | None = None) -> bool:
    e = (cfg.get("digest") or {}).get("email") or {}
    host, to = e.get("smtp_host"), to or e.get("to")
    if not host or not to:
        return False
    password = os.environ.get(e.get("password_env") or "JOBRADAR_SMTP_PASSWORD", "")
    msg = EmailMessage()
    msg["Subject"] = f"JobRadar digest — {datetime.now():%d %b}"
    msg["From"] = e.get("from") or e.get("user") or "jobradar@localhost"
    msg["To"] = to
    msg.set_content(md)
    try:
        with smtplib.SMTP(host, int(e.get("smtp_port", 587)), timeout=20) as s:
            if e.get("starttls", True):
                s.starttls()
            if e.get("user"):
                s.login(e["user"], password)
            s.send_message(msg)
        return True
    except Exception as ex:
        log.warning("digest email failed: %s", ex)
        return False


def run(cfg: dict, uid: int) -> dict:
    md, info = build(cfg, uid)
    user = db.get_user(uid) or {}
    info["emailed"] = send_email(cfg, md, (user.get("prefs") or {}).get("email"))
    return info


def run_all(cfg: dict) -> list[dict]:
    return [run(cfg, u["id"]) for u in db.list_users()]


def latest(uid: int) -> str | None:
    p = db.get_setting("last_digest_path", uid)
    if p and Path(p).exists():
        return Path(p).read_text(encoding="utf-8")
    return None
